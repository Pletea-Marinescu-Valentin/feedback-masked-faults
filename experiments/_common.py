"""Shared helpers for experiment scripts: paths, configs, figure style, LaTeX numbers.

Every number quoted in the paper is written by an experiment into
paper/generated/<experiment>.tex as a LaTeX macro, so the manuscript never
carries a hand-typed result.
"""

